"""Pipeline-document history and standalone export; independent of Qt."""
import copy
import json
from pathlib import Path
import engine
import zipfile
import sys

def runtime_dir():
    return Path(sys._MEIPASS)/'runtime' if getattr(sys,'frozen',False) else Path(__file__).parent

class Document:
    def __init__(self):
        self.pipeline={'version':1,'steps':[]}; self.undo_stack=[]; self.redo_stack=[]
        self.mark_saved()
    @property
    def dirty(self):return self.pipeline!=self.saved_pipeline
    def mark_saved(self):self.saved_pipeline=copy.deepcopy(self.pipeline)
    def load(self,pipeline):
        self.pipeline=engine.validate(pipeline); self.undo_stack=[]; self.redo_stack=[]
        self.mark_saved()
    def commit(self,pipeline):
        updated=engine.validate(pipeline)
        if updated==self.pipeline:return
        self.undo_stack.append(copy.deepcopy(self.pipeline)); self.undo_stack=self.undo_stack[-100:]
        self.pipeline=updated; self.redo_stack=[]
    def undo(self):
        if self.undo_stack:self.redo_stack.append(self.pipeline); self.pipeline=self.undo_stack.pop()
    def redo(self):
        if self.redo_stack:self.undo_stack.append(self.pipeline); self.pipeline=self.redo_stack.pop()

def export_script(path,pipeline):
    pipeline=engine.validate(pipeline)
    source=(runtime_dir()/'engine.py').read_text(encoding='utf-8')
    trailer='\n\nPIPELINE = json.loads('+repr(json.dumps(pipeline))+')\n\nif __name__ == "__main__":\n    run_cli(PIPELINE)\n'
    Path(path).write_text('# Generated by CV2 Image to Script. Requires numpy and opencv-python-headless.\n'+source+trailer,encoding='utf-8')

def export_bundle(path,pipeline):
    pipeline=engine.validate(pipeline); root=runtime_dir()
    with zipfile.ZipFile(path,'w',zipfile.ZIP_DEFLATED) as archive:
        for name in ('engine.py','augmentation.py','dataset.py'):archive.write(root/name,name)
        archive.writestr('recipe.json',json.dumps(pipeline,indent=2))
        archive.writestr('generate.py',"from dataset import main\nif __name__ == '__main__': main(default_recipe='recipe.json')\n")
        archive.writestr('requirements.txt','numpy>=1.26,<3\nopencv-python-headless>=4.10,<6\n')
        archive.writestr('README.txt','Install requirements, then run: python generate.py generate inputs.json --output generated --variants 5 --seed 42\nReplay: python generate.py replay generated/replay.jsonl --row 0 --output replay.png\nManifests use id,image,split and optional mask,boxes,keypoints. Split source data before augmentation. See main application documentation for coordinate conventions.\n')
